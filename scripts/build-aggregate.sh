#ifndef BASE16_COLOR_H__
#define BASE16_COLOR_H__

/**
 * A single color used for Base16 or Base24.
 */
typedef struct base16_color {
    unsigned char r; /** Red channel */
    unsigned char g; /** Green channel */
    unsigned char b; /** Blue channel */
} base16_color;

#endif /* BASE16_COLOR_H__ */

#ifndef BASE16_SCHEME_H__
#define BASE16_SCHEME_H__

/**
 * A Base16 Scheme.
 */
typedef struct base16_scheme {
    const char *name; /** The name of the scheme. */
    base16_color base[24]; /** An array of the base16 colors for the scheme. */
    unsigned char system; /** Which system the scheme was built for, either 16 or 24. */
} base16_scheme;

#endif  /* BASE16_SCHEME_H__ */
EOF

echo ""
echo "/* Base16 schemes */"
for slug in $base16_slugs; do
    echo ""
    echo "#if defined(BASE16_ALL) || defined(BASE16_SCHEME_$(macro_slug "$slug"))"
    echo "#include \"base16-$slug.h\""
    echo "#endif"
done

echo ""
echo "/* Base24 schemes */"
for slug in $base24_slugs; do
    echo ""
    echo "#if defined(BASE24_ALL) || defined(BASE16_ALL) || defined(BASE24_SCHEME_$(macro_slug "$slug"))"
    echo "#include \"base24-$slug.h\""
    echo "#endif"
done

cat <<'EOF'

/* Scheme registry, available when BASE16_SCHEME_LIST is defined. */
#if defined(BASE16_SCHEME_LIST)
#ifndef BASE16_SCHEME_LIST_H__
#define BASE16_SCHEME_LIST_H__

#include <stddef.h> /* size_t, NULL */

/**
 * A NULL-terminated array of pointers to all of the selected schemes.
 */
extern const base16_scheme *base16_scheme_list[];

/**
 * The number of schemes in base16_scheme_list, excluding the trailing NULL.
 */
extern const size_t base16_scheme_list_count;

#endif  /* BASE16_SCHEME_LIST_H__ */

#if defined(BASE16_IMPLEMENTATION) && !defined(BASE16_HEADER_ONLY)
#ifndef BASE16_SCHEME_LIST_IMPLEMENTATION_ONCE
#define BASE16_SCHEME_LIST_IMPLEMENTATION_ONCE

const base16_scheme *base16_scheme_list[] = {
EOF

for slug in $base16_slugs; do
    echo "#if defined(BASE16_ALL) || defined(BASE16_SCHEME_$(macro_slug "$slug"))"
    echo "    &base16_$(symbol_slug "$slug"),"
    echo "#endif"
done
for slug in $base24_slugs; do
    echo "#if defined(BASE24_ALL) || defined(BASE16_ALL) || defined(BASE24_SCHEME_$(macro_slug "$slug"))"
    echo "    &base24_$(symbol_slug "$slug"),"
    echo "#endif"
done

cat <<'EOF'
    NULL /* Sentinel, so that the array is never empty. */
};

const size_t base16_scheme_list_count = sizeof(base16_scheme_list) / sizeof(base16_scheme_list[0]) - 1;

#endif  /* BASE16_SCHEME_LIST_IMPLEMENTATION_ONCE */
#endif  /* BASE16_IMPLEMENTATION */
#endif  /* BASE16_SCHEME_LIST */
EOF
} > "$tmp"

mv "$tmp" "$out"

echo "Generated $out"
