#!/bin/sh
#
# build-aggregate.sh: Generates include/base16.h, the aggregate header that
# exposes every scheme header behind opt-in preprocessor guards.
#
# Usage: scripts/build-aggregate.sh
#
# Run this after regenerating the scheme headers with:
#   tinted-builder-rust build .

set -eu

LC_ALL=C
export LC_ALL

# Always operate from the repository root.
cd "$(dirname "$0")/.."

out="include/base16.h"
tmp="$out.tmp"

# Uppercase a scheme slug and replace dashes with underscores.
# e.g. "atelier-cave-light" -> "ATELIER_CAVE_LIGHT"
macro_slug() {
    printf '%s' "$1" | tr 'a-z-' 'A-Z_'
}

# Replace dashes with underscores, keeping case.
# e.g. "atelier-cave-light" -> "atelier_cave_light"
symbol_slug() {
    printf '%s' "$1" | tr -- '-' '_'
}

base16_slugs=$(ls include/base16-*.h | sed -e 's|^include/base16-||' -e 's|\.h$||' | sort)
base24_slugs=$(ls include/base24-*.h | sed -e 's|^include/base24-||' -e 's|\.h$||' | sort)

{
cat <<'EOF'
/**
 * base16.h: Aggregate header for all Base16 and Base24 color schemes.
 *
 * This file is generated by scripts/build-aggregate.sh. Do not edit it
 * directly. To regenerate it, run:
 *
 *     scripts/build-aggregate.sh
 *
 * Every scheme is opt-in so that including this header costs nothing by
 * default. Define one or more of the following macros before including it:
 *
 * - BASE16_SCHEME_<SLUG>: include a single Base16 scheme, where <SLUG> is the
 *   scheme slug uppercased with dashes replaced by underscores. For example,
 *   define BASE16_SCHEME_DRACULA for base16-dracula.h.
 * - BASE24_SCHEME_<SLUG>: include a single Base24 scheme. For example, define
 *   BASE24_SCHEME_DRACULA for base24-dracula.h.
 * - BASE16_ALL: include every Base16 and Base24 scheme.
 * - BASE24_ALL: include every Base24 scheme.
 * - BASE16_SCHEME_LIST: define a registry of the selected schemes for
 *   enumeration. When BASE16_IMPLEMENTATION is also defined, this provides
 *   base16_scheme_list, a NULL-terminated array of pointers to the selected
 *   schemes, along with base16_scheme_list_count.
 *
 * The usual stb-style macros from the individual scheme headers apply here as
 * well: define BASE16_IMPLEMENTATION in exactly one translation unit to
 * provide the scheme definitions, or BASE16_HEADER_ONLY to suppress them.
 *
